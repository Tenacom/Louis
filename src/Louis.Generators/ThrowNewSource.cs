using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Louis.Generators;

/// <summary>
/// Writes the source files of <see cref="ThrowNewGenerator"/>.
/// </summary>
internal static class ThrowNewSource
{
    // Louis.Generators is packaged in the Louis package.
    private const string ToolPackageName = "Louis";

    private const string IndentUnit = "    ";

    // The compiler takes a file for generated code when its name ends with ".g.cs".
    private const string HintNameSuffix = $".{WellKnownNames.ThrowNew}.g.cs";

    // The compiler also takes a file for generated code when a comment before its first token holds "<auto-generated".
    private const string FileHeader
        = $"""
           // <auto-generated>
           // This file was automatically generated by {ToolPackageName}. DO NOT MODIFY!
           // </auto-generated>

           #nullable enable


           """;

    private static readonly SymbolDisplayFormat HintNameFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted);

    // The attributes of each method, with their arguments. The first three are for the tools that read generated code:
    // a debugger does not step into the method, a coverage tool leaves it out, and a metrics tool does not count it.
    // The last two are for the compiler and for the runtime: the method does not return, and a stack trace leaves it out.
    // The version of this assembly is the version of the Louis package that holds it.
    private static readonly (string Name, string Arguments)[] MethodAttributes = [
        ("System.Diagnostics.DebuggerNonUserCodeAttribute", string.Empty),
        ("System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute", string.Empty),
        (
            "System.CodeDom.Compiler.GeneratedCodeAttribute",
            $"(\"{ToolPackageName}\", \"{ThisAssembly.AssemblyInformationalVersion}\")"),
        (WellKnownNames.DoesNotReturnAttribute, string.Empty),
        (WellKnownNames.StackTraceHiddenAttribute, string.Empty),
    ];

    /// <summary>
    /// Writes the <c>ThrowNew</c> methods of a constructor with <c>ThrowNewAttribute</c>.
    /// </summary>
    /// <param name="context">The context of the constructor.</param>
    /// <returns>The methods, or <see langword="null"/> if the constructor gets none.</returns>
    public static ConstructorSource? ForConstructor(GeneratorAttributeSyntaxContext context)
        => ForConstructorSymbol((IMethodSymbol)context.TargetSymbol, (CSharpCompilation)context.SemanticModel.Compilation);

    /// <summary>
    /// Writes the <c>ThrowNew</c> methods of the primary constructor of a class,
    /// if the constructor has <c>ThrowNewAttribute</c>.
    /// </summary>
    /// <param name="context">The context of the class declaration.</param>
    /// <param name="cancellationToken">A token to cancel the operation.</param>
    /// <returns>The methods, or <see langword="null"/> if the primary constructor gets none.</returns>
    public static ConstructorSource? ForPrimaryConstructor(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var declaration = context.Node;
        var compilation = (CSharpCompilation)context.SemanticModel.Compilation;
        var attributeType = compilation.GetTypeByMetadataName(WellKnownNames.ThrowNewAttribute);

        // GetDeclaredSymbol has a nullable return type, and OfType leaves a null out.
        // The primary constructor is the one constructor that the class declaration itself declares.
        ISymbol?[] declaredSymbols = [context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken)];
        var constructor = declaredSymbols
            .OfType<INamedTypeSymbol>()
            .SelectMany(static type => type.InstanceConstructors)
            .FirstOrDefault(candidate => IsDeclaredBy(candidate, declaration) && HasAttribute(candidate, attributeType));
        return constructor is null ? null : ForConstructorSymbol(constructor, compilation);
    }

    /// <summary>
    /// Writes the source file of a class with <c>ThrowNewForAttribute</c>.
    /// </summary>
    /// <param name="context">The context of the class.</param>
    /// <returns>The source file, or <see langword="null"/> if the class gets no method.</returns>
    public static GeneratedFile? ForExtensionClass(GeneratorAttributeSyntaxContext context)
    {
        var @class = (INamedTypeSymbol)context.TargetSymbol;
        var compilation = (CSharpCompilation)context.SemanticModel.Compilation;
        var attribute = context.Attributes[0];
        var problem = ThrowNewRules.CheckExtensionClass(@class, attribute, compilation, out var exceptionType, out var isPublic);
        if (problem != ThrowNewProblem.None || exceptionType is not INamedTypeSymbol namedType)
        {
            return null;
        }

        var accessibility = SyntaxFacts.GetText(isPublic ? Accessibility.Public : Accessibility.Internal);
        var sources = ThrowNewRules.GetPublicConstructors(namedType)
            .Select(constructor => CreateConstructorSource(@class, exceptionType, constructor, accessibility, compilation));
        return Combine(sources).FirstOrDefault();
    }

    /// <summary>
    /// Combines the methods of the constructors of each class into one source file.
    /// </summary>
    /// <param name="sources">The methods of each constructor.</param>
    /// <returns>One source file for each class, with the methods in a stable order.</returns>
    public static IEnumerable<GeneratedFile> Combine(IEnumerable<ConstructorSource> sources)
        => sources.GroupBy(static source => (source.HintName, source.Opening, source.Closing), CreateFile);

    private static ConstructorSource? ForConstructorSymbol(IMethodSymbol constructor, CSharpCompilation compilation)
    {
        if (ThrowNewRules.CheckConstructor(constructor, compilation) != ThrowNewProblem.None)
        {
            return null;
        }

        var type = constructor.ContainingType;
        var accessibility = SyntaxFacts.GetText(constructor.DeclaredAccessibility);
        return CreateConstructorSource(type, extendedType: null, constructor, accessibility, compilation);
    }

    private static bool IsDeclaredBy(IMethodSymbol constructor, SyntaxNode declaration)
        => constructor.DeclaringSyntaxReferences.Any(reference
            => reference.SyntaxTree == declaration.SyntaxTree && reference.Span == declaration.Span);

    // The attribute type is null in a project that does not reference Louis.
    private static bool HasAttribute(IMethodSymbol constructor, INamedTypeSymbol? attributeType)
        => attributeType is not null
            && constructor.GetAttributes()
                .Any(attribute => SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, attributeType));

    private static GeneratedFile CreateFile(
        (string HintName, string Opening, string Closing) file,
        IEnumerable<ConstructorSource> sources)
    {
        var methods = sources
            .OrderBy(static source => source.ParameterCount)
            .ThenBy(static source => source.Signature, StringComparer.Ordinal)
            .Select(static source => source.Text);
        return new(file.HintName, $"{file.Opening}{string.Join("\n", methods)}{file.Closing}");
    }

    private static ConstructorSource CreateConstructorSource(
        INamedTypeSymbol declaringType,
        ITypeSymbol? extendedType,
        IMethodSymbol constructor,
        string accessibility,
        Compilation compilation)
    {
        // Each block of the file: the namespace, the types from the outermost one, and the extension block.
        List<string> blocks = [];
        if (!declaringType.ContainingNamespace.IsGlobalNamespace)
        {
            blocks.Add($"namespace {SymbolText.NamespaceName(declaringType.ContainingNamespace)}");
        }

        List<INamedTypeSymbol> types = [];
        for (var current = declaringType; current is not null; current = current.ContainingType)
        {
            types.Insert(0, current);
        }

        blocks.AddRange(types.Select(SymbolText.PartialDeclaration));
        if (extendedType is not null)
        {
            blocks.Add($"extension({SymbolText.TypeName(extendedType)})");
        }

        var opening = new StringBuilder(FileHeader);
        var closing = string.Empty;
        var indent = string.Empty;
        foreach (var block in blocks)
        {
            _ = opening.Append(indent).Append(block).Append('\n').Append(indent).Append("{\n");
            closing = $"{indent}}}\n{closing}";
            indent += IndentUnit;
        }

        // The type parameter of the second method takes a name that no type parameter in scope has.
        var typeParameters = types.SelectMany(static type => type.TypeParameters);
        var typeParameterNames = new HashSet<string>(typeParameters.Select(static parameter => parameter.Name));
        var resultType = "T";
        while (typeParameterNames.Contains(resultType))
        {
            resultType += "Result";
        }

        // A hint name takes the full name of the class, with an underscore for each character that a file name may not hold.
        var typeName = declaringType.ToDisplayString(HintNameFormat);
        var hintName = string.Concat(typeName.Select(static c => char.IsLetterOrDigit(c) || c == '.' ? c : '_'));
        var parameters = constructor.Parameters;
        var signature = string.Join(", ", parameters.Select(SymbolText.ParameterDeclaration));
        var text = WriteMethods(constructor, extendedType ?? declaringType, accessibility, signature, resultType, compilation, indent);
        return new($"{hintName}{HintNameSuffix}", opening.ToString(), closing, parameters.Length, signature, text);
    }

    private static string WriteMethods(
        IMethodSymbol constructor,
        ITypeSymbol exceptionType,
        string accessibility,
        string signature,
        string resultType,
        Compilation compilation,
        string indent)
    {
        var exceptionName = SymbolText.TypeName(exceptionType);
        var exceptionId = SymbolText.DocumentationId(exceptionType);
        var constructorId = SymbolText.DocumentationId(constructor);
        var arguments = string.Join(", ", constructor.Parameters.Select(SymbolText.Argument));

        var summary = $"/// Throws a new <see cref=\"{exceptionId}\"/>";
        var attributes = SymbolText.CopiedAttributes(constructor).Concat(GetAvailableAttributes(compilation));
        string[] attributeLines = [.. attributes.Select(static attribute => $"[{attribute}]")];

        // The XML comments of the parameters are the ones that the constructor has for them.
        // The compiler does not resolve inheritdoc. An IDE and a documentation generator do.
        string[] parameterLines = constructor.Parameters.IsEmpty ? [] : [$"/// <inheritdoc cref=\"{constructorId}\" path=\"/param\"/>"];
        string[] lines = [
            "/// <summary>",
            $"{summary}.",
            "/// </summary>",
            .. parameterLines,
            .. attributeLines,
            $"{accessibility} static void {WellKnownNames.ThrowNew}({signature})",
            $"{IndentUnit}=> throw new {exceptionName}({arguments});",
            string.Empty,
            "/// <summary>",
            $"{summary}, where the code needs an expression of type <typeparamref name=\"{resultType}\"/>.",
            "/// </summary>",
            $"/// <typeparam name=\"{resultType}\">The type of the expression.</typeparam>",
            .. parameterLines,
            "/// <returns>This method does not return.</returns>",
            .. attributeLines,
            $"{accessibility} static {resultType} {WellKnownNames.ThrowNew}<{resultType}>({signature})",
            $"{IndentUnit}=> throw new {exceptionName}({arguments});",
        ];

        return string.Concat(lines.Select(line => line.Length == 0 ? "\n" : $"{indent}{line}\n"));
    }

    private static IEnumerable<string> GetAvailableAttributes(Compilation compilation)
        => MethodAttributes
            .Where(attribute => CanName(compilation, attribute.Name))
            .Select(static attribute => $"global::{attribute.Name}{attribute.Arguments}");

    // A method gets an attribute only when the name of the attribute means one type in the project.
    // A type that the project declares wins over a type of a reference.
    // With no such type, the references must hold one accessible type of that name:
    // the compiler rejects a name that two references declare, with CS0433.
    private static bool CanName(Compilation compilation, string metadataName)
    {
        var accessibleTypes = compilation.GetTypesByMetadataName(metadataName)
            .Where(type => compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            .ToList();
        return accessibleTypes.Count == 1
            || accessibleTypes.Exists(type => SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly));
    }
}
