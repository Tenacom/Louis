        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("extension(global::System.Exception)");
        await Assert.That(text).Contains("internal static void ThrowNew()");
        await Assert.That(text).DoesNotContain("public");
    }

    [Test]
    public async Task ClosedGenericExceptionType_GetsMethods()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public class E<T> : Exception
            {
                public E(T value)
                {
                }
            }

            [ThrowNewFor(typeof(E<int>))]
            internal static partial class X;
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("extension(global::E<int>)");
        await Assert.That(text).Contains("""<see cref="T:E`1"/>""");
        await Assert.That(text).Contains("""<inheritdoc cref="M:E`1.#ctor(`0)" path="/param"/>""");
        await Assert.That(text).Contains("internal static void ThrowNew(int value)");
        await Assert.That(text).Contains("=> throw new global::E<int>(value);");
    }

    [Test]
    public async Task ConstructorWithParameterOfPointerType_GetsNoMethod()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public unsafe class E : Exception
            {
                public E()
                {
                }

                public E(int* pointer)
                {
                }

                public E(int*[] pointers)
                {
                }

                public E(delegate*<void> function)
                {
                }
            }

            [ThrowNewFor(typeof(E))]
            internal static partial class X;
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("internal static void ThrowNew()");
        await Assert.That(text).DoesNotContain("pointer");
        await Assert.That(text).DoesNotContain("function");
    }

    [Test]
    public async Task EachClass_GetsFileOfItsOwn()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            namespace N
            {
                [ThrowNewFor(typeof(InvalidOperationException))]
                internal static partial class X;

                [ThrowNewFor(typeof(NotSupportedException))]
                internal static partial class Y;
            }
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        await Assert.That(run.Files.Keys).IsEquivalentTo(["N.X.ThrowNew.g.cs", "N.Y.ThrowNew.g.cs"]);
        await Assert.That(run.Files["N.X.ThrowNew.g.cs"]).Contains("extension(global::System.InvalidOperationException)");
        await Assert.That(run.Files["N.Y.ThrowNew.g.cs"]).Contains("extension(global::System.NotSupportedException)");
    }

    // The reference assemblies of .NET Standard 2.0 have no nullable annotations,
    // and neither DoesNotReturnAttribute nor StackTraceHiddenAttribute.
    [Test]
    public async Task NetStandard20_GetsMethodsThatAcceptNull_WithoutAttributesItLacks()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            [ThrowNewFor(typeof(ArgumentException))]
            internal static partial class X;
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.CompileForNetStandard20(source, TestCompiler.AttributeSource));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("internal static void ThrowNew()");
        await Assert.That(text).Contains("internal static void ThrowNew(string? message)");
        await Assert.That(text).Contains("internal static void ThrowNew(string? message, global::System.Exception? innerException)");
        await Assert.That(text).Contains("internal static void ThrowNew(string? message, string? paramName)");
        await Assert.That(text).Contains("[global::System.Diagnostics.DebuggerNonUserCodeAttribute]");
        await Assert.That(text).Contains("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]");
        await Assert.That(text).Contains("[global::System.CodeDom.Compiler.GeneratedCodeAttribute(");
        await Assert.That(text).DoesNotContain("DoesNotReturn");
        await Assert.That(text).DoesNotContain("StackTraceHidden");
    }

    [Test]
    public async Task AttributeDeclaredByProject_GoesOnMethods()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            namespace System.Diagnostics.CodeAnalysis
            {
                [AttributeUsage(AttributeTargets.Method, Inherited = false)]
                internal sealed class DoesNotReturnAttribute : Attribute;
            }

            [ThrowNewFor(typeof(ArgumentException))]
            internal static partial class X;
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.CompileForNetStandard20(source, TestCompiler.AttributeSource));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("[global::System.Diagnostics.CodeAnalysis.DoesNotReturnAttribute]");
        await Assert.That(text).DoesNotContain("StackTraceHidden");
    }
