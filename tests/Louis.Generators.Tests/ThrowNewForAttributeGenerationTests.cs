    [Test]
    public async Task Class_GetsTwoExtensionMethodsForEachPublicConstructor()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            namespace N
            {
                public class E : Exception
                {
                    public E(string m)
                        : base(m)
                    {
                    }

                    public E()
                    {
                    }

                    internal E(int hidden)
                    {
                    }

                    protected E(long hidden)
                    {
                    }
                }

                [ThrowNewFor(typeof(E))]
                internal static partial class X;
            }
            """;

        var expected = $$"""
            // <auto-generated>
            // This file was automatically generated by Louis. DO NOT MODIFY!
            // </auto-generated>

            #nullable enable

            namespace N
            {
                partial class X
                {
                    extension(global::N.E)
                    {
                        /// <summary>
                        /// Throws a new <see cref="T:N.E"/>.
                        /// </summary>
                        [global::System.Diagnostics.DebuggerNonUserCodeAttribute]
                        [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
                        [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Louis", "{{TestCompiler.GeneratorVersion}}")]
                        [global::System.Diagnostics.CodeAnalysis.DoesNotReturnAttribute]
                        [global::System.Diagnostics.StackTraceHiddenAttribute]
                        internal static void ThrowNew()
                            => throw new global::N.E();

                        /// <summary>
                        /// Throws a new <see cref="T:N.E"/>, where the code needs an expression of type <typeparamref name="T"/>.
                        /// </summary>
                        /// <typeparam name="T">The type of the expression.</typeparam>
                        /// <returns>This method does not return.</returns>
                        [global::System.Diagnostics.DebuggerNonUserCodeAttribute]
                        [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
                        [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Louis", "{{TestCompiler.GeneratorVersion}}")]
                        [global::System.Diagnostics.CodeAnalysis.DoesNotReturnAttribute]
                        [global::System.Diagnostics.StackTraceHiddenAttribute]
                        internal static T ThrowNew<T>()
                            => throw new global::N.E();

                        /// <summary>
                        /// Throws a new <see cref="T:N.E"/>.
                        /// </summary>
                        /// <inheritdoc cref="M:N.E.#ctor(System.String)" path="/param"/>
                        [global::System.Diagnostics.DebuggerNonUserCodeAttribute]
                        [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
                        [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Louis", "{{TestCompiler.GeneratorVersion}}")]
