    [Test]
    public async Task PublicProperty_MakesMethodsPublic()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            [ThrowNewFor(typeof(InvalidOperationException), Public = true)]
            public static partial class X;
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["X.ThrowNew.g.cs"];
        await Assert.That(text).Contains("extension(global::System.InvalidOperationException)");
        await Assert.That(text).Contains("public static void ThrowNew(string? message, global::System.Exception? innerException)");
        await Assert.That(text).Contains("public static T ThrowNew<T>(string? message, global::System.Exception? innerException)");
        await Assert.That(text).DoesNotContain("internal");
    }

    [Test]
