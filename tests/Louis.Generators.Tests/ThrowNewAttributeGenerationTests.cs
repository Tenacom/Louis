    [Test]
    public async Task Parameters_KeepAttributesThatSupplyCallerInformation()
    {
        const string source = """
            using System;
            using System.Diagnostics.CodeAnalysis;
            using System.Runtime.CompilerServices;
            using Louis.Diagnostics;

            public partial class E : Exception
            {
                [ThrowNew]
                public E(
                    object value,
                    [CallerArgumentExpression(nameof(value))] string expression = "",
                    [CallerMemberName] string member = "",
                    [CallerFilePath] string file = "",
                    [CallerLineNumber] int line = 0,
                    [AllowNull] string other = "")
                {
                }
            }
            """;

        const string attributes = "global::System.Runtime.CompilerServices";
        string[] expectedParameters = [
            "object value",
            $"[{attributes}.CallerArgumentExpressionAttribute(\"value\")] string expression = \"\"",
            $"[{attributes}.CallerMemberNameAttribute()] string member = \"\"",
            $"[{attributes}.CallerFilePathAttribute()] string file = \"\"",
            $"[{attributes}.CallerLineNumberAttribute()] int line = 0",
            "string other = \"\"",
        ];

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        await Assert.That(run.Files["E.ThrowNew.g.cs"]).Contains($"static void ThrowNew({string.Join(", ", expectedParameters)})");
    }

    [Test]
    public async Task Methods_KeepAttributesThatTheCallerOfConstructorNeeds()
    {
        const string source = """
            using System;
            using System.ComponentModel;
            using System.Diagnostics.CodeAnalysis;
            using Louis.Diagnostics;

            public partial class E : Exception
            {
                [ThrowNew]
                [Obsolete("Use another constructor.", true)]
                public E(int a)
                {
                }

                [ThrowNew]
                [Obsolete]
                public E(long a)
                {
                }

                [ThrowNew]
                [Experimental("TEST0001", UrlFormat = "https://example.com/{0}")]
                public E(string a)
                {
                }

                [ThrowNew]
                [RequiresAssemblyFiles("Files.")]
                [RequiresDynamicCode("Dynamic code.")]
                [RequiresUnreferencedCode("Reflection.", Url = "https://example.com/")]
                public E(double a)
                {
                }

                [ThrowNew]
                [EditorBrowsable(EditorBrowsableState.Never)]
                public E(char a)
                {
                }
            }
            """;

        const string attributes = "global::System.Diagnostics.CodeAnalysis";
        string[] expectedAttributes = [
            """[global::System.ObsoleteAttribute("Use another constructor.", true)]""",
            "[global::System.ObsoleteAttribute()]",
            $$"""[{{attributes}}.ExperimentalAttribute("TEST0001", UrlFormat = "https://example.com/{0}")]""",
            $$"""[{{attributes}}.RequiresAssemblyFilesAttribute("Files.")]""",
            $$"""[{{attributes}}.RequiresDynamicCodeAttribute("Dynamic code.")]""",
            $$"""[{{attributes}}.RequiresUnreferencedCodeAttribute("Reflection.", Url = "https://example.com/")]""",
        ];

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["E.ThrowNew.g.cs"];
        foreach (var attribute in expectedAttributes)
        {
            await Assert.That(text).Contains(attribute);
        }

        await Assert.That(text).DoesNotContain("EditorBrowsable");
    }

