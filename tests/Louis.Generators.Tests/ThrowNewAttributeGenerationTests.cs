    [Test]
    public async Task Constructor_GetsTwoMethods()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            namespace N;

            public sealed partial class E : Exception
            {
                [ThrowNew]
                public E(string m)
                    : base(m)
                {
                }
            }
            """;

        var expected = $$"""
            // <auto-generated>
            // This file was automatically generated by Louis. DO NOT MODIFY!
            // </auto-generated>

            #nullable enable

            namespace N
            {
                partial class E
                {
                    /// <summary>
                    /// Throws a new <see cref="T:N.E"/>.
                    /// </summary>
                    /// <inheritdoc cref="M:N.E.#ctor(System.String)" path="/param"/>
                    [global::System.Diagnostics.DebuggerNonUserCodeAttribute]
                    [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
                    [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Louis", "{{TestCompiler.GeneratorVersion}}")]
                    [global::System.Diagnostics.CodeAnalysis.DoesNotReturnAttribute]
                    [global::System.Diagnostics.StackTraceHiddenAttribute]
                    public static void ThrowNew(string m)
                        => throw new global::N.E(m);

                    /// <summary>
                    /// Throws a new <see cref="T:N.E"/>, where the code needs an expression of type <typeparamref name="T"/>.
                    /// </summary>
                    /// <typeparam name="T">The type of the expression.</typeparam>
                    /// <inheritdoc cref="M:N.E.#ctor(System.String)" path="/param"/>
                    /// <returns>This method does not return.</returns>
                    [global::System.Diagnostics.DebuggerNonUserCodeAttribute]
                    [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
                    [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Louis", "{{TestCompiler.GeneratorVersion}}")]
                    [global::System.Diagnostics.CodeAnalysis.DoesNotReturnAttribute]
                    [global::System.Diagnostics.StackTraceHiddenAttribute]
                    public static T ThrowNew<T>(string m)
                        => throw new global::N.E(m);
                }
            }

            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        await Assert.That(run.Files.Keys).IsEquivalentTo(["N.E.ThrowNew.g.cs"]);
        await Assert.That(run.Files["N.E.ThrowNew.g.cs"]).IsEqualTo(expected.ReplaceLineEndings("\n"));
    }

    [Test]
    public async Task SeveralConstructors_GetMethodsInOneFile_OrderedByParameterCountThenBySignature()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public partial class E : Exception
            {
                [ThrowNew]
                public E(string message, Exception? innerException)
                    : base(message, innerException)
                {
                }

                [ThrowNew]
                public E(string message)
                    : base(message)
                {
                }

                [ThrowNew]
                public E(int code)
                {
                }

                [ThrowNew]
                public E()
                {
                }

                public E(double untouched)
                {
                }
            }
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["E.ThrowNew.g.cs"];
        string[] signatures = [
            "void ThrowNew()",
            "void ThrowNew(int code)",
            "void ThrowNew(string message)",
            "void ThrowNew(string message, global::System.Exception? innerException)",
        ];

        var positions = signatures.Select(signature => text.IndexOf(signature, StringComparison.Ordinal)).ToArray();
        await Assert.That(positions).DoesNotContain(-1);
        await Assert.That(positions).IsInOrder();
        await Assert.That(text).DoesNotContain("double");
    }

