    [Test]
    public async Task NestedClass_GetsMethodsInsideEachContainingType()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public partial record struct A
            {
                public partial record B
                {
                    public partial struct C
                    {
                        public partial interface ID
                        {
                            public partial class E : Exception
                            {
                                [ThrowNew]
                                public E()
                                {
                                }
                            }
                        }
                    }
                }
            }
            """;

        const string expectedStart = """
            // <auto-generated>
            // This file was automatically generated by Louis. DO NOT MODIFY!
            // </auto-generated>

            #nullable enable

            partial record struct A
            {
                partial record B
                {
                    partial struct C
                    {
                        partial interface ID
                        {
                            partial class E
                            {
                                /// <summary>
            """;

        const string expectedEnd = """
                                    => throw new global::A.B.C.ID.E();
                            }
                        }
                    }
                }
            }

            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["A.B.C.ID.E.ThrowNew.g.cs"];
        await Assert.That(text).StartsWith(expectedStart.ReplaceLineEndings("\n"));
        await Assert.That(text).EndsWith(expectedEnd.ReplaceLineEndings("\n"));
    }

    [Test]
    public async Task GenericClass_GetsMethodsWithTypeParameterOfUnusedName()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public partial class E<T, TResult> : Exception
            {
                [ThrowNew]
                public E(T value, TResult other)
                {
                }
            }
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["E_T__TResult_.ThrowNew.g.cs"];
        await Assert.That(text).Contains("partial class E<T, TResult>");
        await Assert.That(text).Contains("""<see cref="T:E`2"/>""");
        await Assert.That(text).Contains("""<inheritdoc cref="M:E`2.#ctor(`0,`1)" path="/param"/>""");
        await Assert.That(text).Contains("public static void ThrowNew(T value, TResult other)");
        await Assert.That(text).Contains("""<typeparam name="TResultResult">""");
        await Assert.That(text).Contains("public static TResultResult ThrowNew<TResultResult>(T value, TResult other)");
        await Assert.That(text).Contains("=> throw new global::E<T, TResult>(value, other);");
    }

    [Test]
    public async Task Parameters_KeepModifiers()
    {
        const string source = """
            using System;
            using Louis.Diagnostics;

            public partial class E : Exception
            {
                [ThrowNew]
                public E(ref int a, out int b, in int c, ref readonly int d, params string[] @params)
                {
                    b = 0;
                }
            }
            """;

        var run = TestCompiler.RunGenerator(TestCompiler.Compile(source));

        await Assert.That(run.Problems).IsEmpty();
        var text = run.Files["E.ThrowNew.g.cs"];
        await Assert.That(text).Contains("ThrowNew(ref int a, out int b, in int c, ref readonly int d, params string[] @params)");
        await Assert.That(text).Contains("=> throw new global::E(ref a, out b, in c, in d, @params);");
    }

